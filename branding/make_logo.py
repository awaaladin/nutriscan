# ---------- PNGs ----------
def gradient_circle(d):
    """Gold gradient disc of diameter d with a transparent outside."""
    g = Image.new("RGB", (d, d))
    px = g.load()
    for y in range(d):
        for x in range(d):
            t = (x + y) / (2 * (d - 1))
            px[x, y] = tuple(round(GOLD_A[i] + (GOLD_B[i] - GOLD_A[i]) * t) for i in range(3))
    mask = Image.new("L", (d, d), 0)
    ImageDraw.Draw(mask).ellipse((0, 0, d - 1, d - 1), fill=255)
    return g, mask


def icon_mask(side):
    """The scanner icon as a mask, `side` pixels wide for the 24-unit box."""
    k = side / 24
    m = Image.new("L", (side, side), 0)
    d = ImageDraw.Draw(m)
    sc = lambda r: tuple(v * k for v in r)
    for outer, inner in RINGS:
        d.rectangle(sc(outer), fill=255)
        d.rectangle(sc(inner), fill=0)
    for r in DOTS:
        d.rectangle(sc(r), fill=255)
    for poly in CORNERS:
        d.polygon([(x * k, y * k) for x, y in poly], fill=255)
    return m


def mark(size, rounded=True):
    """The full square logo (green tile + gold disc + icon) at `size` px, supersampled 4x."""
    big = size * 4
    img = Image.new("RGB", (big, big), GREEN)
    disc_d = round(big * 340 / 512)
    disc, dmask = gradient_circle(disc_d)
    off = (big - disc_d) // 2
    img.paste(disc, (off, off), dmask)
    side = round(big * 240 / 512)  # 24 units * scale 10 = 240 of 512
    im = icon_mask(side)
    img.paste(Image.new("RGB", (side, side), GREEN), ((big - side) // 2, (big - side) // 2), im)
    out = img.resize((size, size), Image.LANCZOS).convert("RGBA")
    if rounded:
        m = Image.new("L", (big, big), 0)
        ImageDraw.Draw(m).rounded_rectangle((0, 0, big - 1, big - 1), radius=round(big * 112 / 512), fill=255)
        out.putalpha(m.resize((size, size), Image.LANCZOS))
    return out


