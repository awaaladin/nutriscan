"""Builds every logo asset from ONE geometry: the loading-screen mark (gold circle + QR scanner
icon on deep green). Run: python branding/make_logo.py"""
import os
from PIL import Image, ImageDraw, ImageFont

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
GREEN = (0x0B, 0x2E, 0x22)
GREEN_HEX = "#0B2E22"
GOLD_A, GOLD_B = (0xE1, 0xC7, 0x66), (0xB8, 0x86, 0x0B)
CREAM = (0xF7, 0xF6, 0xF2)
SCAN_GREEN = (0x8C, 0xC6, 0x3F)

# Material "qr_code_scanner" in a 24-unit box.
RINGS = [((5, 5, 11, 11), (6.5, 6.5, 9.5, 9.5)), ((13, 5, 19, 11), (14.5, 6.5, 17.5, 9.5)), ((5, 13, 11, 19), (6.5, 14.5, 9.5, 17.5))]
DOTS = [(13, 13, 14.5, 14.5), (14.5, 14.5, 16, 16), (16, 13, 17.5, 14.5), (13, 16, 14.5, 17.5),
        (14.5, 17.5, 16, 19), (16, 16, 17.5, 17.5), (17.5, 14.5, 19, 16), (17.5, 17.5, 19, 19)]
CORNERS = [[(22, 7), (20, 7), (20, 4), (17, 4), (17, 2), (22, 2)],
           [(22, 22), (17, 22), (17, 20), (20, 20), (20, 17), (22, 17)],
           [(2, 22), (2, 17), (4, 17), (4, 20), (7, 20), (7, 22)],
           [(2, 2), (7, 2), (7, 4), (4, 4), (4, 7), (2, 7)]]


def rect_path(r):
    x0, y0, x1, y1 = r
    return f"M{x0},{y0}H{x1}V{y1}H{x0}Z"


def icon_path():
    parts = []
    for outer, inner in RINGS:
        parts += [rect_path(outer), rect_path(inner)]
    parts += [rect_path(d) for d in DOTS]
    for poly in CORNERS:
        parts.append("M" + "L".join(f"{x},{y}" for x, y in poly) + "Z")
    return "".join(parts)


ICON = icon_path()


def write(path, text):
    os.makedirs(os.path.dirname(path), exist_ok=True)
    with open(path, "w", encoding="utf-8", newline="\n") as f:
        f.write(text)


